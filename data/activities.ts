// Helper function to get activities by city
// This mimics what would be a database query
export function getActivitiesByCity(city: string): Activity[] {
  return activities.filter((activity) => activity.city === city);
}

// Helper function to get activities by category
// This mimics what would be a database query
export function getActivitiesByCategory(category: string): Activity[] {
  return activities.filter((activity) => activity.category === category);
}

// Helper function to get activities by city and category
// This mimics what would be a database query
export function getActivitiesByCityAndCategory(city: string, category: string): Activity[] {
  return activities.filter((activity) => activity.city === city && activity.category === category);
}

// Helper function to get activity by ID
// This mimics what would be a database query
export function getActivityById(id: string): Activity | undefined {
  return activities.find((activity) => activity.id === id);
}

// Helper function to get activity by city and slug
// This mimics what would be a database query
export function getActivityBySlug(city: string, slug: string): Activity | undefined {
  return activities.find((activity) => activity.city === city && activity.slug === slug);
}

// Helper function to get similar activities (same category or tags)
// This mimics what would be a database query
export function getSimilarActivities(activity: Activity, limit: number = 3): Activity[] {
  return activities
    .filter((a) =>
      a.id !== activity.id &&
      a.city === activity.city &&
      (a.category === activity.category ||
       (activity.tags && a.tags?.some(tag => activity.tags?.includes(tag))))
    )
    .slice(0, limit);
}

// Helper function to get all activities
// This mimics what would be a database query
export function getAllActivities(): Activity[] {
  return activities;
}
